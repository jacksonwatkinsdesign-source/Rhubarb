// font.js — 5x7 bitmap font.
//
// Each glyph is written as 7 rows of exactly 5 cells separated by '/'.
// Hand-concatenating 35-char strings is how you get a font that silently
// shears one glyph and ruins every word containing it, so the rows are
// explicit and validated at load.
